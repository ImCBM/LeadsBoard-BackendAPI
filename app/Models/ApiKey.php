<?php

namespace App\Models;

use App\Enums\ApiKeyType;
use App\Models\ApiScope as ApiScopeModel;
use App\Models\Tier;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * Normalized ApiKey model adhering to 3NF.
 *
 * Tiers are linked via tier_id foreign key.
 * Scopes are linked via api_key_scopes pivot table.
 */
class ApiKey extends Model
{
    protected $fillable = [
        'user_id',
        'tier_id',
        'name',
        'key_type',
        'key',
        'plain_text_prefix',
        'rate_limit_per_minute',
        'allowed_ips',
        'is_active',
        'last_used_at',
        'expires_at',
    ];

    protected function casts(): array
    {
        return [
            'key_type' => ApiKeyType::class,
            'tier_id' => 'integer',
            'allowed_ips' => 'array',
            'is_active' => 'boolean',
            'rate_limit_per_minute' => 'integer',
            'last_used_at' => 'datetime',
            'expires_at' => 'datetime',
        ];
    }

    // ── Relationships ──────────────────────────────────────────────

    /**
     * The user who owns this API key (nullable for standalone system keys).
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * The tier assigned to this API key.
     */
    public function tier(): BelongsTo
    {
        return $this->belongsTo(Tier::class);
    }

    /**
     * Scopes assigned directly to this API key via pivot.
     */
    public function scopes(): BelongsToMany
    {
        return $this->belongsToMany(ApiScopeModel::class, 'api_key_scopes');
    }

    /**
     * Audit traces generated by this key.
     */
    public function traces(): HasMany
    {
        return $this->hasMany(ApiTrace::class);
    }

    // ── Validation ─────────────────────────────────────────────────

    /**
     * Check if this key is currently valid (active + not expired).
     */
    public function isValid(): bool
    {
        if (!$this->is_active) {
            return false;
        }

        if ($this->expires_at && $this->expires_at->isPast()) {
            return false;
        }

        return true;
    }

    /**
     * Check if the key is a public (client-safe) key.
     */
    public function isPublic(): bool
    {
        $val = $this->key_type instanceof ApiKeyType ? $this->key_type->value : $this->key_type;
        return $val === 'public';
    }

    /**
     * Check if the key is a secret (server-side) key.
     */
    public function isSecret(): bool
    {
        $val = $this->key_type instanceof ApiKeyType ? $this->key_type->value : $this->key_type;
        return $val === 'secret';
    }

    // ── Scope Checking ─────────────────────────────────────────────

    /**
     * Check if this key has a specific scope granted.
     *
     * Respects:
     * - Wildcard '*' (full access)
     * - Resource wildcards 'leads:*'
     * - Key type restrictions (public keys cannot have write scopes)
     */
    public function hasScope(string $requiredScope): bool
    {
        // Public keys cannot have write/mutation scopes
        if ($this->isPublic()) {
            $keyType = $this->key_type instanceof ApiKeyType ? $this->key_type : ApiKeyType::tryFrom($this->key_type);
            if ($keyType) {
                $forbidden = $keyType->forbiddenScopes();
                if (in_array($requiredScope, $forbidden)) {
                    return false;
                }
            }
        }

        $scopeNames = $this->scopes->pluck('name')->all();

        // Wildcard full access
        if (in_array('*', $scopeNames)) {
            return true;
        }

        // Direct match
        if (in_array($requiredScope, $scopeNames)) {
            return true;
        }

        // Resource wildcard match (e.g. leads:*)
        [$resource] = explode(':', $requiredScope, 2);
        if (in_array("{$resource}:*", $scopeNames)) {
            return true;
        }

        return false;
    }

    /**
     * Get all effective scopes, respecting key type restrictions.
     */
    public function getEffectiveScopes(): array
    {
        $scopeNames = $this->scopes->pluck('name')->all();

        if (empty($scopeNames)) {
            return [];
        }

        if ($this->isPublic()) {
            $keyType = $this->key_type instanceof ApiKeyType ? $this->key_type : ApiKeyType::tryFrom($this->key_type);
            $forbidden = $keyType ? $keyType->forbiddenScopes() : [];

            if (in_array('*', $scopeNames)) {
                return array_values(array_diff(\App\Enums\ApiScope::values(), $forbidden));
            }

            return array_values(array_diff($scopeNames, $forbidden));
        }

        return $scopeNames;
    }

    // ── Rate Limiting ──────────────────────────────────────────────

    /**
     * Get the effective rate limit for this key.
     * null = use tier default, integer = key-level budget.
     */
    public function getEffectiveRateLimit(): ?int
    {
        return $this->rate_limit_per_minute;
    }

    // ── Usage Tracking ─────────────────────────────────────────────

    /**
     * Record that this key was just used.
     */
    public function recordUsage(): void
    {
        $this->update(['last_used_at' => now()]);
    }

    // ── IP Validation ──────────────────────────────────────────────

    /**
     * Check if the given IP is allowed for this key.
     * Returns true if no IP whitelist is set (unrestricted).
     */
    public function isIpAllowed(string $ip): bool
    {
        $allowedIps = $this->allowed_ips;

        // No whitelist = all IPs allowed
        if (empty($allowedIps)) {
            return true;
        }

        return \Symfony\Component\HttpFoundation\IpUtils::checkIp($ip, $allowedIps);
    }
}

<?php

namespace App\Models;

use App\Enums\ApiKeyType;
use App\Enums\ApiScope;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class ApiKey extends Model
{
    protected $fillable = [
        'user_id',
        'name',
        'key_type',
        'key',
        'plain_text_prefix',
        'scopes',
        'rate_limit_per_minute',
        'tier',
        'allowed_ips',
        'metadata',
        'is_active',
        'last_used_at',
        'expires_at',
    ];

    protected function casts(): array
    {
        return [
            'key_type' => ApiKeyType::class,
            'scopes' => 'array',
            'allowed_ips' => 'array',
            'metadata' => 'array',
            'is_active' => 'boolean',
            'rate_limit_per_minute' => 'integer',
            'last_used_at' => 'datetime',
            'expires_at' => 'datetime',
        ];
    }

    // ── Relationships ──────────────────────────────────────────────

    /**
     * The user who owns this API key (nullable for standalone system keys).
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Audit traces generated by this key.
     */
    public function traces(): HasMany
    {
        return $this->hasMany(ApiTrace::class);
    }

    // ── Validation ─────────────────────────────────────────────────

    /**
     * Check if this key is currently valid (active + not expired).
     */
    public function isValid(): bool
    {
        if (!$this->is_active) {
            return false;
        }

        if ($this->expires_at && $this->expires_at->isPast()) {
            return false;
        }

        return true;
    }

    /**
     * Check if the key is a public (client-safe) key.
     */
    public function isPublic(): bool
    {
        return $this->key_type === ApiKeyType::Public;
    }

    /**
     * Check if the key is a secret (server-side) key.
     */
    public function isSecret(): bool
    {
        return $this->key_type === ApiKeyType::Secret;
    }

    // ── Scope Checking ─────────────────────────────────────────────

    /**
     * Check if this key has a specific scope granted.
     *
     * Respects:
     * - Wildcard '*' (full access)
     * - Resource wildcards 'leads:*'
     * - Key type restrictions (public keys cannot have write scopes)
     */
    public function hasScope(string $requiredScope): bool
    {
        $scopes = $this->scopes ?? [ApiScope::WILDCARD];

        // Public keys can never have write/delete scopes regardless of assignment
        if ($this->isPublic()) {
            $forbidden = $this->key_type->forbiddenScopes();
            if (in_array($requiredScope, $forbidden)) {
                return false;
            }
        }

        return ApiScope::scopesSatisfy($scopes, $requiredScope);
    }

    /**
     * Get all effective scopes, respecting key type restrictions.
     */
    public function getEffectiveScopes(): array
    {
        $scopes = $this->scopes ?? [ApiScope::WILDCARD];

        if ($this->isPublic()) {
            $forbidden = $this->key_type->forbiddenScopes();
            // If wildcard, expand to all scopes minus forbidden
            if (in_array(ApiScope::WILDCARD, $scopes)) {
                return array_values(array_diff(ApiScope::values(), $forbidden));
            }
            return array_values(array_diff($scopes, $forbidden));
        }

        return $scopes;
    }

    // ── Rate Limiting ──────────────────────────────────────────────

    /**
     * Get the effective rate limit for this key.
     * null = use system default, 0 = unlimited.
     */
    public function getEffectiveRateLimit(): ?int
    {
        return $this->rate_limit_per_minute;
    }

    // ── Usage Tracking ─────────────────────────────────────────────

    /**
     * Record that this key was just used.
     */
    public function recordUsage(): void
    {
        $this->update(['last_used_at' => now()]);
    }

    // ── IP Validation ──────────────────────────────────────────────

    /**
     * Check if the given IP is allowed for this key.
     * Returns true if no IP whitelist is set (unrestricted).
     */
    public function isIpAllowed(string $ip): bool
    {
        $allowedIps = $this->allowed_ips;

        // No whitelist = all IPs allowed
        if (empty($allowedIps)) {
            return true;
        }

        return in_array($ip, $allowedIps);
    }
}
